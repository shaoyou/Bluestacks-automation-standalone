def _model_template_lists(model: Optional[Dict[str, Any]]) -> Dict[str, List[np.ndarray]]:
    """Normalize learned (single template per digit) and bundled (variant list)
    models into one lookup; learned templates win per digit."""
    merged: Dict[str, List[np.ndarray]] = {
        digit: list(entries) for digit, entries in _bundled_quantity_templates().items()
    }
    learned = (model or {}).get("templates", {}) if isinstance(model, dict) else {}
    for digit, template in (learned or {}).items():
        array = np.asarray(template, dtype=np.float32)
        if array.size == 0:
            continue
        merged[str(digit)] = [array]
    return merged


# Enclosed-counter count per digit in the game font (0/4/6/9 one hole,
# 8 two holes, the rest none). Structural sanity check on top of the
# template vote: the game's flag+stem '1' has no hole, which is exactly the
# shape tesseract misreads as 4/7.
_EXPECTED_DIGIT_HOLES = {"0": 1, "4": 1, "6": 1, "8": 2, "9": 1}


def _glyph_hole_count(binary_mask: np.ndarray) -> int:
    """Background components not connected to the border (4-connectivity)."""
    padded = np.pad(~binary_mask, 1, constant_values=True)
    height, width = padded.shape
    labels = np.zeros((height, width), dtype=np.int32)
    current = 0
    for sy in range(height):
        for sx in range(width):
            if padded[sy, sx] and labels[sy, sx] == 0:
                current += 1
                labels[sy, sx] = current
                stack = [(sy, sx)]
                while stack:
                    cy, cx = stack.pop()
                    for ny, nx in ((cy - 1, cx), (cy + 1, cx), (cy, cx - 1), (cy, cx + 1)):
                        if 0 <= ny < height and 0 <= nx < width and padded[ny, nx] and labels[ny, nx] == 0:
                            labels[ny, nx] = current
                            stack.append((ny, nx))
    border = set(labels[0]) | set(labels[-1]) | set(labels[:, 0]) | set(labels[:, -1])
    return sum(
        1
        for label in range(1, current + 1)
        if label not in border and int((labels == label).sum()) >= 3
    )


def _glyph_stem_drift(binary_mask: np.ndarray) -> float:
    """Horizontal centroid drift (columns) from the upper to the lower third
    of the glyph's lower half.

    The game's '7' sweeps its diagonal to the left (strong negative drift)
    while every '1' variant keeps a vertical stem (drift near zero). This
    separates the two where template distance alone is ambiguous.
    """
    height = binary_mask.shape[0]
    lower = binary_mask[int(height * 0.5):]
    rows = []
    for row in lower:
        total = int(row.sum())
        if total >= 2:
            rows.append(float(np.average(np.arange(row.size), weights=row)))
    if len(rows) < 6:
        return 0.0
    third = max(1, len(rows) // 3)
    return float(np.mean(rows[-third:]) - np.mean(rows[:third]))


def _classify_quantity_glyphs(glyphs: List[np.ndarray], model: Dict[str, Any]) -> Tuple[Optional[int], float]:
    templates = _model_template_lists(model)
    if not glyphs or any(str(digit) not in templates for digit in range(10)):
        return None, 0.0
    predicted: List[str] = []
    distances: List[float] = []
    for glyph in glyphs:
        glyph_pixels = glyph[:-3]
        glyph_features = glyph[-3:]
        binary = glyph_pixels.reshape(40, 24) > 0.5
        holes = _glyph_hole_count(binary)
        drift = _glyph_stem_drift(binary)
        ranked = []
        for digit, entries in templates.items():
            best = math.inf
            for template in entries:
                distance = float(np.mean((glyph_pixels - template[:-3]) ** 2)) + float(
                    np.mean((glyph_features - template[-3:]) ** 2)
                ) * 3.0
                best = min(best, distance)
            if _EXPECTED_DIGIT_HOLES.get(digit, 0) != holes:
                best += 0.18
            if digit == "7" and drift > -0.5:
                # vertical stem: this is a '1' variant, not a '7'
                best += 0.12
            if digit == "1" and drift < -1.8:
                # strong left sweep: this is a '7'
                best += 0.12
            ranked.append((best, digit))
        ranked.sort()
        distances.append(ranked[0][0])
        predicted.append(ranked[0][1])
    confidence = max(0.0, min(1.0, 1.0 - float(np.mean(distances)) * 5.0))
    return int("".join(predicted)), confidence


def read_quantity(tile: Image.Image, digit_model: Optional[Dict[str, Any]] = None) -> Tuple[Optional[int], float]:
    glyphs = extract_quantity_glyphs(tile)
    if not glyphs:
        # The game only paints a number when a stack exists; rewards without a
        # visible quantity (equipment, single pulls) are one item.
        no_glyph_default = digit_model.get("no_glyph_default") if isinstance(digit_model, dict) else None
        return (int(no_glyph_default) if isinstance(no_glyph_default, int) else 1), 0.85
    learned_quantity, learned_confidence = _classify_quantity_glyphs(glyphs, digit_model)
    # The bundled/learned templates are built from this exact game font, while
    # tesseract demonstrably misreads its flag-stem '1' as 4/7, so the
    # template read wins down to a loose confidence floor.
    if learned_quantity is not None and learned_confidence >= 0.30 and str(learned_quantity)[0] != "0":
        return learned_quantity, max(0.80, learned_confidence)
    # Per-glyph tesseract fallback on clean isolated masks. The mask must be
    # inverted (black digits on white): tesseract silently returns nothing on
    # white-on-black input, which previously produced most of the empty reads.
    digits_text = []
    for glyph in glyphs:
        mask = (glyph[:-3].reshape(40, 24) > 0.5)
        candidate = Image.fromarray(((~mask) * 255).astype("uint8"))
        enlarged = candidate.resize((candidate.width * 6, candidate.height * 6), Image.Resampling.LANCZOS)
        digit = _tesseract_single_digit(enlarged)
        if digit is None:
            return None, 0.0
        digits_text.append(str(digit))
    number = int("".join(digits_text))
    if str(number)[0] == "0":
        return None, 0.0
    return number, 0.62


def _tesseract_single_digit(enlarged: Image.Image) -> Optional[int]:
    try:
        with tempfile.NamedTemporaryFile(suffix=".png") as temporary:
            enlarged.save(temporary.name)
            result = subprocess.run(
                ["tesseract", temporary.name, "stdout", "--psm", "10", "-c", "tessedit_char_whitelist=0123456789"],
                capture_output=True,
                text=True,
                timeout=8,
                check=False,
            )
    except (FileNotFoundError, subprocess.TimeoutExpired):
        return None
    digits = "".join(char for char in result.stdout if char.isdigit())
    if len(digits) != 1:
        return None
    return int(digits)


def _encode_icon_template(template: np.ndarray) -> str:
    pixels = (template[: ICON_TEMPLATE_SIZE * ICON_TEMPLATE_SIZE] * 255.0).round().astype(np.uint8)
    return base64.b64encode(pixels.tobytes()).decode("ascii")


def _item_templates(item: Dict[str, Any]) -> List[np.ndarray]:
    templates = []
    pixel_count = ICON_TEMPLATE_SIZE * ICON_TEMPLATE_SIZE
    for stored in item.get("templates", []):
        try:
            raw = base64.b64decode(str(stored))
        except (ValueError, TypeError):
            continue
        if len(raw) == pixel_count:
            pixels = np.frombuffer(raw, dtype=np.uint8).astype(np.float32).reshape(-1) / 255.0
            templates.append(np.concatenate([pixels, np.zeros(3, dtype=np.float32)]))
        elif len(raw) == pixel_count + 3:
            full = np.frombuffer(raw, dtype=np.uint8).astype(np.float32) / 255.0
            templates.append(np.concatenate([full[:pixel_count], np.zeros(3, dtype=np.float32)]))
    return templates


_ICON_MATRIX_CACHE: Dict[int, Tuple[int, np.ndarray, List[Dict[str, Any]]]] = {}


def _catalog_template_matrix(catalog: Dict[str, Any]) -> Tuple[np.ndarray, List[Dict[str, Any]]]:
    """All catalog icon templates as one matrix plus the owning item per row,
    cached until the catalog gains items or templates."""
    items = catalog.setdefault("items", [])
    stamp = sum(len(item.get("templates", [])) for item in items) * 1000 + len(items)
    cached = _ICON_MATRIX_CACHE.get(id(catalog))
    if cached and cached[0] == stamp:
        return cached[1], cached[2]
    rows: List[np.ndarray] = []
    owners: List[Dict[str, Any]] = []
    for item in items:
        for stored in _item_templates(item):
            rows.append(stored)
            owners.append(item)
    matrix = np.stack(rows) if rows else np.zeros((0, ICON_TEMPLATE_SIZE * ICON_TEMPLATE_SIZE), dtype=np.float32)
    _ICON_MATRIX_CACHE[id(catalog)] = (stamp, matrix, owners)
    return matrix, owners


def classify_item(
    diffused_tile: Image.Image,
    catalog: Dict[str, Any],
    rarity: Optional[str] = None,
) -> Tuple[Dict[str, Any], float, np.ndarray]:
    """Match a reward tile's icon-core template against the catalog; create a
    new unknown item when nothing is close enough. Tiles of different rarity
    classes can never be the same item, so a known mismatching rarity blocks
    the match."""
    items = catalog.setdefault("items", [])
    template = icon_core_template(diffused_tile)
    icon_hash = perceptual_hash(extract_icon(diffused_tile))
    matrix, owners = _catalog_template_matrix(catalog)
    best: Optional[Dict[str, Any]] = None
    best_distance = math.inf
    for row_index, owner in enumerate(owners):
        distance = icon_template_distance(template, matrix[row_index])
        if distance < best_distance:
            best, best_distance = owner, distance
    # Legacy entries recorded only perceptual hashes.
    for item in items:
        if best is not None and best_distance <= ICON_MATCH_MAX_MSE:
            break
        for candidate in item.get("hashes", []):
            if hamming(icon_hash, str(candidate)) <= 6:
                best, best_distance = item, ICON_MATCH_MAX_MSE * 0.8
                break
    if best is not None and best_distance <= ICON_MATCH_MAX_MSE:
        stored = _item_templates(best)
        if len(stored) < ICON_MAX_TEMPLATES and all(
            icon_template_distance(template, existing) > ICON_MATCH_MAX_MSE * 0.7 for existing in stored
        ):
            best.setdefault("templates", []).append(_encode_icon_template(template))
            _ICON_MATRIX_CACHE.pop(id(catalog), None)
        if rarity and not best.get("rarity"):
            best["rarity"] = rarity
        return best, max(0.0, 1.0 - best_distance / ICON_MATCH_MAX_MSE), template

    created = {
        "item_id": f"unknown_{icon_hash}",
        "name": "待标注物品",
        "category": "unknown",
        "hashes": [icon_hash],
        "templates": [_encode_icon_template(template)],
        **({"rarity": rarity} if rarity else {}),
        "created_at": datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
    }
    items.append(created)
    _ICON_MATRIX_CACHE.pop(id(catalog), None)
    return created, 0.0, template


